"""Sound effects (and a few optional text-to-speech lines) for the warehouse show.

The WAV files in ``controllers/warehouse_mission/sounds/`` are generated by
``tools/generate_assets.py``. They play through the robot's ``Speaker
"speaker"`` device. Every sound is rate limited (per sound, and globally) so
that repeated events never turn into noise, and ``S`` mutes everything.
Text-to-speech (``Speaker.speak``) is optional: the first failure disables it.

Two bugs of the Webots R2025a controller library are worked around here:

1. ``speaker.c`` writes the play request of *every* sound the library knows,
   and for each sound that is not being (re)played in the same step it writes
   a stray 4-byte field. As soon as two different sounds have been played,
   Webots misreads the request and reports garbage file names ("Invalid URL",
   "Impossible to play"). So every step that plays a sound re-sends *all*
   known sounds: the requested ones, the ones still playing unchanged (Webots
   then only updates their gain), and the finished ones at an inaudible gain.
2. A stop and a play of the same sound in one step stop *every* sound, so a
   sound that must restart while it is still (silently) playing is stopped in
   one frame and played in the next.

Hence :meth:`Audio.play` only queues; :meth:`Audio.update` (once per frame)
talks to the C library, which keeps our byte strings (they live as long as
the controller: the Python binding's temporary ``str.encode`` buffers do not).
"""

from __future__ import annotations

import ctypes
import time
import wave
from pathlib import Path

try:  # the controller module exists only inside Webots
    from controller import Speaker
except ImportError:  # pragma: no cover - offline import for docs/tests
    Speaker = None  # type: ignore[assignment]
try:  # the binding's ctypes library (see the module docstring)
    from controller.wb import wb as _wb
except Exception:  # noqa: BLE001 - another binding: fall back to Speaker.playSound
    _wb = None

SOUND_NAMES = (
    "boot_chime",
    "beep",
    "beep_go",
    "rfid_ping",
    "lock_on",
    "pickup",
    "delivered_fanfare",
    "safety_buzz",
    "kidnap_whoosh",
    "obstacle_thud",
    "ui_click",
)

# Base volume of each sound (0..1): UI ticks stay in the background, rewards pop.
VOLUME: dict[str, float] = {
    "boot_chime": 0.7,
    "beep": 0.55,
    "beep_go": 0.7,
    "rfid_ping": 0.35,
    "lock_on": 0.65,
    "pickup": 0.7,
    "delivered_fanfare": 0.8,
    "safety_buzz": 0.6,
    "kidnap_whoosh": 0.75,
    "obstacle_thud": 0.8,
    "ui_click": 0.3,
}
# Minimum wall-clock time between two plays of the same sound (s), at least its length.
MIN_INTERVAL: dict[str, float] = {
    "rfid_ping": 1.2,
    "safety_buzz": 0.8,
    "lock_on": 1.0,
    "ui_click": 0.06,
    "beep": 0.15,
    "beep_go": 0.45,
    "obstacle_thud": 0.6,
    "kidnap_whoosh": 1.0,
    "pickup": 0.85,
    "delivered_fanfare": 2.5,
    "boot_chime": 2.0,
}
GLOBAL_WINDOW = 0.25  # s
GLOBAL_MAX = 3  # at most this many sounds start within GLOBAL_WINDOW (UI clicks excepted)
SILENT = 1e-4  # gain of a re-sent finished sound (-80 dB); 0 would not be sent at all


def _wav_seconds(path: Path) -> float:
    try:
        with wave.open(str(path), "rb") as clip:
            return clip.getnframes() / float(clip.getframerate())
    except Exception:  # noqa: BLE001 - unknown length: assume a long one
        return 2.0


class Audio:
    """Rate-limited sound effects on the robot's speaker.

    Args:
        robot: the Supervisor (to find the ``speaker`` device).
        sound_dir: folder with the WAV files.
        enabled: False for ``--no-sound`` (nothing is ever played).
        volume_scale: global volume multiplier (0 = nothing reaches Webots;
            the autotest uses 0 unless ``--sound``/``--volume`` is given).
        tts: allow a few text-to-speech lines.
    """

    def __init__(
        self,
        robot,
        sound_dir: Path,
        enabled: bool = True,
        volume_scale: float = 1.0,
        tts: bool = True,
    ):
        self.speaker = None
        try:
            self.speaker = robot.getDevice("speaker")
        except Exception:  # noqa: BLE001 - a missing device must not stop the show
            self.speaker = None
        if self.speaker is None and enabled:
            print("warehouse_mission: no Speaker 'speaker' on the robot; sound is off.", flush=True)
        self.enabled = enabled and self.speaker is not None and Speaker is not None
        self.muted = False
        self.volume_scale = float(volume_scale)
        self.tts_ok = bool(tts) and self.enabled
        self._paths: dict[str, str] = {}
        self._cpaths: dict[str, bytes] = {}  # kept alive: the C library keeps the pointers
        self._ctexts: dict[str, bytes] = {}
        self._seconds: dict[str, float] = {}
        for name in SOUND_NAMES:
            path = Path(sound_dir) / f"{name}.wav"
            if path.is_file():
                self._paths[name] = str(path)
                self._cpaths[name] = str(path).encode()
                self._seconds[name] = _wav_seconds(path)
        missing = [name for name in SOUND_NAMES if name not in self._paths]
        if missing and self.enabled:
            print(f"warehouse_mission: missing sound files: {', '.join(missing)}", flush=True)
        self._tag = getattr(self.speaker, "_tag", None)
        self._raw = _wb is not None and self._tag is not None
        # Sounds the C library knows: name -> [end (wall s), gain or None if silent, pitch].
        self._known: dict[str, list] = {}
        self._queue: list[tuple[str, float, float]] = []
        self._last: dict[str, float] = {}
        self._recent: list[float] = []
        self.played = 0  # statistics (QA)
        # The default text-to-speech engine ("pico", American English) is what we
        # want. Do not call setLanguage(): in the R2025a Python binding it calls
        # wb_speaker_set_engine() with the language string.

    # ------------------------------------------------------------------
    @property
    def active(self) -> bool:
        return self.enabled and not self.muted

    def toggle_mute(self) -> bool:
        """Mute/unmute; returns True if sound is now on."""
        self.muted = not self.muted
        if self.muted:
            self.stop_all()
        return not self.muted

    def play(
        self, name: str, volume: float | None = None, pitch: float = 1.0, force: bool = False
    ) -> bool:
        """Queue one sound effect unless it is rate limited; returns True if it will play."""
        if not self.active or name not in self._paths:
            return False
        now = time.monotonic()
        if not force and now - self._last.get(name, -1e9) < MIN_INTERVAL.get(name, 0.2):
            return False
        if name != "ui_click":
            self._recent = [t for t in self._recent if now - t < GLOBAL_WINDOW]
            if not force and len(self._recent) >= GLOBAL_MAX:
                return False
            self._recent.append(now)
        self._last[name] = now
        gain = max(
            0.0, min(1.0, (VOLUME.get(name, 0.6) if volume is None else volume) * self.volume_scale)
        )
        if gain <= 0.0:
            return False  # silent autotest: Webots would ignore it anyway
        if not self._raw:  # another binding: best effort
            try:
                Speaker.playSound(
                    self.speaker, self.speaker, self._paths[name], gain, pitch, 0.0, False
                )
            except Exception as exc:  # noqa: BLE001
                print(
                    f"warehouse_mission: sound disabled ({type(exc).__name__}: {exc})", flush=True
                )
                self.enabled = False
                return False
        else:
            self._queue = [item for item in self._queue if item[0] != name]
            self._queue.append((name, gain, max(0.05, float(pitch))))
        self.played += 1
        return True

    def update(self) -> None:
        """Send the queued sounds to Webots (call once per frame; see the module docstring)."""
        if not self._queue or not self._raw:
            return
        now = time.monotonic()
        try:
            busy = {
                name
                for name, _, _ in self._queue
                if name in self._known and now < self._known[name][0]
            }
            if busy:  # still playing (audibly or silently): stop now, play in the next frame
                for name in busy:
                    _wb.wb_speaker_stop(self._tag, self._cpaths[name])
                    self._known[name][0] = now
                return
            requested = {name: (gain, pitch) for name, gain, pitch in self._queue}
            self._queue = []
            for name, state in self._known.items():
                if name in requested:
                    continue
                end, gain, pitch = state
                if now < end:  # still playing: re-sent unchanged
                    self._send(name, gain if gain is not None else SILENT, pitch)
                else:  # finished: Webots restarts it, inaudibly
                    self._send(name, SILENT, 1.0)
                    state[:] = [now + self._seconds[name], None, 1.0]
            for name, (gain, pitch) in requested.items():
                self._send(name, gain, pitch)
                self._known[name] = [now + self._seconds[name] / pitch, gain, pitch]
        except Exception as exc:  # noqa: BLE001
            print(f"warehouse_mission: sound disabled ({type(exc).__name__}: {exc})", flush=True)
            self.enabled = False

    def _send(self, name: str, gain: float, pitch: float) -> None:
        _wb.wb_speaker_play_sound(
            self._tag,
            self._tag,
            self._cpaths[name],
            ctypes.c_double(gain),
            ctypes.c_double(pitch),
            ctypes.c_double(0.0),
            0,
        )

    def say(self, text: str, volume: float = 0.9) -> bool:
        """Speak one short line with Webots' text-to-speech (optional, off after an error)."""
        gain = max(0.0, min(1.0, volume * self.volume_scale))
        if not (self.tts_ok and self.active) or gain <= 0.0:
            return False
        try:
            if self.speaker.isSpeaking():
                return False
            if self._raw:
                ctext = self._ctexts.setdefault(text, text.encode("ascii", "replace"))
                _wb.wb_speaker_speak(self._tag, ctext, ctypes.c_double(gain))
            else:
                self.speaker.speak(text, gain)
        except Exception:  # noqa: BLE001 - no TTS engine on this platform: stay quiet
            self.tts_ok = False
            return False
        return True

    def stop_all(self) -> None:
        self._queue = []
        if self.speaker is None:
            return
        try:
            self.speaker.stop()  # no argument (NULL): stop every sound of this speaker
        except Exception:  # noqa: BLE001
            return
        now = time.monotonic()
        for state in self._known.values():
            state[0] = min(state[0], now)
