    def test_bayes_given_all_sensors(self, bayes_given_all_sensors):
        """Tests the posterior calculation for a few specific cases."""
        # Case 1: A typical Structural Bracing
        # High weight, thick, rigid, metal
        posteriors_bracing = bayes_given_all_sensors(820.0, 2, 0, 1)
        correct_bracing = [0.0000, 0.9895, 0.0000, 0.0000, 0.0105]
        for o, c in zip(posteriors_bracing, correct_bracing, strict=False):
            self.assertAlmostEqual(o, c, delta=0.01)

        # Case 2: A typical 3D Printed Product
        # Low-mid weight, thin, flexible, plastic
        posteriors_printed = bayes_given_all_sensors(150.0, 0, 1, 0)
        correct_printed = [0.9994, 0.0000, 0.0000, 0.0000, 0.0006]
        for o, c in zip(posteriors_printed, correct_printed, strict=False):
            self.assertAlmostEqual(o, c, delta=0.01)

    def test_make_decision(self, make_decision):
        """Tests the decision logic for different posterior distributions."""
        # For these posteriors the min-expected-cost action happens to coincide
        # with the class carrying the highest posterior.

        # Case 1: PCB Board is most likely
        posteriors1 = [0.1, 0.1, 0.7, 0.05, 0.05]
        decision1 = make_decision(posteriors1)
        self.assertEqual(decision1, Item.PCB_BOARD.value)

        # Case 2: 3D Printed Product is most likely
        posteriors2 = [0.9, 0.01, 0.01, 0.04, 0.04]
        decision2 = make_decision(posteriors2)
        self.assertEqual(decision2, Item.PRINTED_PRODUCT.value)

        # Case 3: Motor is most likely
        posteriors3 = [0.1, 0.1, 0.1, 0.1, 0.6]
        decision3 = make_decision(posteriors3)
        self.assertEqual(decision3, Item.MOTOR.value)

