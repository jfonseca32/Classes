    def test_get_item_prior_pmf(self, get_item_prior_pmf):
        """Tests if the prior probabilities are set correctly."""
        correct = [0.3, 0.2, 0.35, 0.1, 0.05]
        output = get_item_prior_pmf()
        self.assertEqual(len(output), len(correct))
        for o, c in zip(output, correct, strict=False):
            self.assertAlmostEqual(o, c, 4)

    def test_sample_item(self, sample_item):
        """Tests if the item sampling matches the prior distribution."""
        outputs = {i: 0 for i in range(5)}
        correct = [0.3, 0.2, 0.35, 0.1, 0.05]
        num_samples = 100000
        for _ in range(num_samples):
            outputs[sample_item()] += 1
        for i in range(5):
            self.assertAlmostEqual(outputs[i] / num_samples, correct[i], delta=0.01)

    def test_sample_weight(self, sample_weight):
        """Tests if weight sampling matches the specified means and std devs."""
        num_samples = 100000
        correct_params = np.array([[150, 75], [800, 400], [50, 25], [250, 125], [600, 300]])
        for i in range(len(Item)):
            item_class = Item(i)
